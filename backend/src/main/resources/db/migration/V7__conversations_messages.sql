-- Conversations are shared by a canonical unordered pair of users.
CREATE TABLE conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low_id BIGINT NOT NULL,
    user_high_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversation_low FOREIGN KEY (user_low_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_high FOREIGN KEY (user_high_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT uq_conversation_pair UNIQUE (user_low_id, user_high_id),
    CONSTRAINT chk_conversation_pair_order CHECK (user_low_id < user_high_id)
);

CREATE TABLE conversation_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    body VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation(id) ON DELETE CASCADE,
    CONSTRAINT fk_message_sender FOREIGN KEY (sender_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT chk_message_body_not_blank CHECK (TRIM(body) <> '')
);
CREATE INDEX idx_message_conversation_order ON conversation_message (conversation_id, id DESC);

CREATE TABLE conversation_user_state (
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    last_read_message_id BIGINT,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_conversation_user_state PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT fk_state_conversation FOREIGN KEY (conversation_id) REFERENCES conversation(id) ON DELETE CASCADE,
    CONSTRAINT fk_state_user FOREIGN KEY (user_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT fk_state_last_read FOREIGN KEY (last_read_message_id) REFERENCES conversation_message(id) ON DELETE SET NULL
);
CREATE INDEX idx_conversation_state_user ON conversation_user_state (user_id, conversation_id);

