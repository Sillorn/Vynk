-- PN-009: accounts and profiles with SQL integrity

CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    username_lower VARCHAR(30),
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

UPDATE user_account SET username_lower = LOWER(username);
ALTER TABLE user_account ALTER COLUMN username_lower SET NOT NULL;
CREATE UNIQUE INDEX idx_user_account_username_lower ON user_account (username_lower);

CREATE TRIGGER trg_user_account_lowercase_insert
BEFORE INSERT ON user_account
FOR EACH ROW
CALL "com.vynk.shared.persistence.LowercaseUsernameTrigger";

CREATE TRIGGER trg_user_account_lowercase_update
BEFORE UPDATE ON user_account
FOR EACH ROW
CALL "com.vynk.shared.persistence.LowercaseUsernameTrigger";

-- Username must be 3-30 lowercase latin letters only
ALTER TABLE user_account
    ADD CONSTRAINT chk_user_account_username_format
    CHECK (REGEXP_LIKE(username, '^[a-z]{3,30}$'));

ALTER TABLE user_account
    ADD CONSTRAINT chk_user_account_status
    CHECK (status IN ('ACTIVE', 'DISABLED'));

CREATE TABLE profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    first_name_lower VARCHAR(100),
    last_name_lower VARCHAR(100),
    headline VARCHAR(200) NOT NULL,
    summary VARCHAR(2000) NOT NULL,
    location VARCHAR(200),
    links_json CLOB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_profile_user_account FOREIGN KEY (user_id) REFERENCES user_account(id) ON DELETE CASCADE
);

UPDATE profile SET first_name_lower = LOWER(first_name), last_name_lower = LOWER(last_name);
CREATE UNIQUE INDEX idx_profile_user_id ON profile (user_id);
CREATE INDEX idx_profile_name ON profile (first_name_lower, last_name_lower);

CREATE TRIGGER trg_profile_lowercase_insert
BEFORE INSERT ON profile
FOR EACH ROW
CALL "com.vynk.shared.persistence.LowercaseProfileNameTrigger";

CREATE TRIGGER trg_profile_lowercase_update
BEFORE UPDATE ON profile
FOR EACH ROW
CALL "com.vynk.shared.persistence.LowercaseProfileNameTrigger";
