-- PN-017: full structured profile schema

CREATE TABLE profile_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    company VARCHAR(200) NOT NULL,
    location VARCHAR(200),
    start_date DATE NOT NULL,
    end_date DATE,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    description VARCHAR(4000),
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_experience_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE,
    CONSTRAINT chk_profile_experience_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX idx_profile_experience_profile ON profile_experience (profile_id, sort_order);

CREATE TABLE profile_education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    school VARCHAR(200) NOT NULL,
    degree VARCHAR(200),
    field_of_study VARCHAR(200),
    start_date DATE,
    end_date DATE,
    description VARCHAR(4000),
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_education_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE,
    CONSTRAINT chk_profile_education_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE INDEX idx_profile_education_profile ON profile_education (profile_id, sort_order);

CREATE TABLE profile_certification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    issuer VARCHAR(200),
    issue_date DATE,
    expiration_date DATE,
    credential_url VARCHAR(500),
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_certification_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE
);

CREATE INDEX idx_profile_certification_profile ON profile_certification (profile_id, sort_order);

CREATE TABLE profile_project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(4000),
    url VARCHAR(500),
    start_date DATE,
    end_date DATE,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_project_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE
);

CREATE INDEX idx_profile_project_profile ON profile_project (profile_id, sort_order);

CREATE TABLE profile_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_skill_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE
);

CREATE INDEX idx_profile_skill_profile ON profile_skill (profile_id, sort_order);

CREATE TABLE profile_language (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    proficiency VARCHAR(50),
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_language_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE
);

CREATE INDEX idx_profile_language_profile ON profile_language (profile_id, sort_order);

CREATE TABLE profile_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    label VARCHAR(100) NOT NULL,
    url VARCHAR(500) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_profile_link_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE
