CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    actor_username VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_id) REFERENCES user_account(id) ON DELETE CASCADE
);
CREATE INDEX idx_notification_recipient_order ON notification (recipient_id, id DESC);
