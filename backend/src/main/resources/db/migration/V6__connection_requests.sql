-- PN-034: directed connection requests. Accepted pairs are stored canonically in V5.
CREATE TABLE connection_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_request_sender FOREIGN KEY (sender_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT fk_request_recipient FOREIGN KEY (recipient_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT uq_connection_request_direction UNIQUE (sender_id, recipient_id),
    CONSTRAINT chk_connection_request_not_self CHECK (sender_id <> recipient_id),
    CONSTRAINT chk_connection_request_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED'))
);
CREATE INDEX idx_connection_request_recipient_status
    ON connection_request (recipient_id, status, created_at DESC, id DESC);
CREATE INDEX idx_connection_request_sender_status
    ON connection_request (sender_id, status, created_at DESC, id DESC);
