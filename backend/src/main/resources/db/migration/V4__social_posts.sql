-- PN-027: posts, comments, and likes with ownership and cascading post deletion.

CREATE TABLE post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL,
    content VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_post_author FOREIGN KEY (author_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT chk_post_content_nonblank CHECK (CHAR_LENGTH(TRIM(content)) > 0)
);
CREATE INDEX idx_post_created ON post (created_at DESC, id DESC);
CREATE INDEX idx_post_author_created ON post (author_id, created_at DESC, id DESC);

CREATE TABLE post_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES user_account(id) ON DELETE CASCADE,
    CONSTRAINT chk_comment_content_nonblank CHECK (CHAR_LENGTH(TRIM(content)) > 0)
);
CREATE INDEX idx_comment_post_created ON post_comment (post_id, created_at, id);

CREATE TABLE post_like (
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_post_like PRIMARY KEY (post_id, user_id),
    CONSTRAINT fk_like_post FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE,
    CONSTRAINT fk_like_user FOREIGN KEY (user_id) REFERENCES user_account(id) ON DELETE CASCADE
);
CREATE INDEX idx_post_like_user ON post_like (user_id, post_id);
